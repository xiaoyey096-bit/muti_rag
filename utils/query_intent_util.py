"""查询意图识别工具

目前只识别一类会显著改变回答策略的意图：用户在问"有没有图 / 想看图"。
这类问题若仍走通用 ANSWER_PROMPT + 联网综述，会先输出一大段产品百科再补一句
"没有图片"，答非所问。识别出来后：联网分支跳过、本地含图切片优先、改用直答模板。
对任意产品通用（不写死任何型号/文档名）。
"""

import re

# 形式一：动词/存在词 + (修饰) + 图类名词。如"有dgx spark产品相关的图吗""给我看看接线图"
_IMG_REQUEST_RE = re.compile(
    r"(有|有没有|是否有|有无|能提供|提供|展示|看看|给我|发一下|发|想要|需要|求)"
    r"[^。？?！!\n]{0,16}"
    r"(图片|图|照片|示意图|截面图|接线图|结构图|外观图|产品图|实物图)"
)
# 形式二：图类名词 + 疑问尾。如"…的图吗""图片有没有"
_IMG_QUESTION_RE = re.compile(
    r"(图片|图|照片|示意图|截面图|接线图|结构图|外观图|产品图|实物图)"
    r"[^。？?！!\n]{0,8}"
    r"(吗|么|呢|有没有|有吗|存在)"
)
# 形式三：直接索要图片清单。如"图片有哪些""都有哪些图"
_IMG_LIST_RE = re.compile(r"(图片|图|照片)(有哪些|都有哪些|列表|清单)")


def is_image_query(text: str) -> bool:
    """判断用户是否在询问/索要图片（存在性或展示），而非普通技术问答。"""
    s = str(text or "")
    if not s:
        return False
    return bool(_IMG_REQUEST_RE.search(s) or _IMG_QUESTION_RE.search(s) or _IMG_LIST_RE.search(s))


# 普通技术问句中提及图片（如"解释接口布局图里每个接口的作用"）：
# 不改变检索策略，仅触发图题级过滤，命中后走 VL 读图作答。
_IMG_MENTION_RE = re.compile(
    r"(图片|照片|示意图|截面图|接线图|结构图|外观图|实物图|产品图|面板图|布局图|接口图|电路图|原理图|框图|图表|图纸"
    r"|图中|图里|看图|读图|这张图|该图|此图)"
)


def mentions_image(text: str) -> bool:
    """问句是否提及图片内容（用于普通问答分支决定是否读图）。"""
    return bool(_IMG_MENTION_RE.search(str(text or "")))